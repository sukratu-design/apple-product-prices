// Generates a static HTML page per product in /prices/<slug>/, the /prices/ hub, the sitemap, and the
// product links in index.html, world/index.html and llms.txt. Every price is written into the HTML so search
// engines and AI tools that don't run JavaScript can read it.
// Run by scripts/build_prices.py after it writes prices.js; can also be run on its own: node scripts/build-pages.mjs
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://apple-product-prices.com";
const MARK = "Generated by scripts/build-pages.mjs";

// Load prices.js and assets/core.js exactly as the browser does, so configurations and formatting match the site.
const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT, "prices.js"), "utf8"), ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT, "assets/core.js"), "utf8"), ctx);
const { P, ORDER, configs, fmt, toUSD } = ctx.window.APP;
const C = P.countries;

// ---------- helpers ----------
const esc = s => String(s).replace(/[&<>"]/g, ch => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[ch]);
const slugify = s => s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const usd = n => "$" + Math.round(n).toLocaleString("en-US");
const longDate = iso => new Date(iso + "T00:00:00Z").toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric", timeZone: "UTC" });
const monthYear = iso => new Date(iso + "T00:00:00Z").toLocaleDateString("en-US", { month: "long", year: "numeric", timeZone: "UTC" });
const byName = codes => [...codes].sort((a, b) => C[a].label.localeCompare(C[b].label));
const taxNote = c => C[c].tax === "excluded" ? "excl. sales tax" : (c === "in" ? "MRP, incl. GST" : "incl. tax");
const UPDATED = P.updated, FX = P.fx;

// The product's full name, as people search for it.
function fullName(ck, p) {
  const paren = s => s.replace(/ · (.+)$/, " ($1)");
  switch (ck) {
    case "iphone": return p.n.startsWith("iPhone") ? p.n : "iPhone " + p.n;
    case "ipad": case "mac": return paren(`${p.n} ${p.s}`);
    case "watch": return paren(`${p.n.startsWith("Watch") ? "Apple " + p.n : "Apple Watch " + p.n} ${p.s}`);
    case "vision": return paren(`Apple ${p.n} · ${p.s}`);
    case "home": return /generation/.test(p.s) ? `${p.n} (${p.s})` : p.n;
    default: return p.n;
  }
}

// Configuration groups: iPads get a Wi-Fi table and a Wi-Fi + Cellular table; everything else one table.
function groups(p) {
  const keep = list => list.filter(x => x[1].some(v => v != null)).map(x => ({ label: x[0], prices: x[1] }));
  if (p.wifi) return [{ name: "Wi-Fi", list: keep(configs(p, "wifi")) }, { name: "Wi-Fi + Cellular", list: keep(configs(p, "cellular")) }];
  return [{ name: null, list: keep(configs(p)) }];
}

// ---------- collect products ----------
const products = [];
for (const ck of P.order) {
  const cat = P.categories[ck];
  for (const p of cat.products) {
    if (p.src !== "apple") continue; // Hermès: US press prices only, no country comparison to show
    const gs = groups(p).filter(g => g.list.length);
    if (!gs.length) continue;
    const entry = gs[0].list[0];
    const sold = ORDER.filter((c, i) => entry.prices[i] != null);
    if (sold.length < 2) continue;
    const name = fullName(ck, p);
    const rows = sold.map(c => {
      const local = entry.prices[ORDER.indexOf(c)];
      return { c, local, usd: toUSD(c, local) };
    }).sort((a, b) => a.usd - b.usd);
    const configLabel = (p.wifi ? "Wi-Fi · " : "") + entry.label;
    products.push({ ck, cat, p, name, slug: slugify(name), groups: gs, entry, configLabel, sold, rows,
      worldKey: `${ck}-${p.id}` });
  }
}
const seen = new Set();
for (const x of products) {
  if (seen.has(x.slug)) throw new Error("Duplicate product page slug: " + x.slug);
  seen.add(x.slug);
}

