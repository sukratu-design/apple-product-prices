// ---------- product pages ----------
function productPage(x, i) {
  const { ck, cat, name, slug, groups: gs, entry, configLabel, rows, sold } = x;
  const url = `${SITE}/prices/${slug}/`;
  const n = sold.length;
  const lo = rows[0], hi = rows[rows.length - 1];
  const us = rows.find(r => r.c === "us");
  const usLine = us ? `In the United States it starts at ${fmt("us", us.local)} (${esc(configLabel)}, before sales tax).` : `It is not sold in the US online store.`;
  const title = `${name} price in ${n} countries`;
  const description = `${name} list price at Apple's online store in ${n} countries, in local currency and US dollars`
    + (us ? `: from ${fmt("us", us.local)} in the US.` : ".") + ` Checked ${monthYear(UPDATED)}.`;

  const pct = r => {
    if (!us || r.c === "us") return "";
    const d = (r.usd / us.usd - 1) * 100, s = Math.round(d);
    return `<span class="${s > 0 ? "up" : s < 0 ? "down" : ""}">${s > 0 ? "+" : s < 0 ? "−" : "±"}${Math.abs(s)}%</span>`;
  };
  const entryTable = `<div class="tw"><table>
        <caption>${esc(name)}, ${esc(configLabel)}: list price by country, cheapest first in US dollars</caption>
        <thead><tr><th class="n">#</th><th>Country</th><th class="n">Local price</th><th class="n">In US dollars</th>${us ? '<th class="n">vs US</th>' : ""}<th>Taxes</th></tr></thead>
        <tbody>
${rows.map((r, k) => `          <tr${r.c === "us" ? ' class="hl"' : ""}><td class="n">${k + 1}</td><th scope="row">${esc(C[r.c].label)}</th><td class="n">${esc(fmt(r.c, r.local))}</td><td class="n">${usd(r.usd)}</td>${us ? `<td class="n">${pct(r)}</td>` : ""}<td>${taxNote(r.c)}</td></tr>`).join("\n")}
        </tbody>
      </table></div>`;

  const configTables = gs.map(g => {
    const codes = byName(ORDER.filter((c, k) => g.list.some(cf => cf.prices[k] != null)));
    return `<div class="tw"><table class="sticky">
        <caption>${esc(name)}${g.name ? " · " + esc(g.name) : ""}: every configuration, in local currency</caption>
        <thead><tr><th>Country</th>${g.list.map(cf => `<th class="n">${esc(cf.label)}</th>`).join("")}</tr></thead>
        <tbody>
${codes.map(c => { const k = ORDER.indexOf(c); return `          <tr><th scope="row">${esc(C[c].label)}</th>${g.list.map(cf => cf.prices[k] == null ? '<td class="n na">–</td>' : `<td class="n">${esc(fmt(c, cf.prices[k]))}</td>`).join("")}</tr>`; }).join("\n")}
        </tbody>
      </table></div>`;
  }).join("\n      ");

  const siblings = products.filter(y => y.ck === ck && y !== x);
  const nConfigs = gs.reduce((a, g) => a + g.list.length, 0);
  const cheapestTax = rows.find(r => C[r.c].tax !== "excluded");

  return `${head({ title: `${title} · Apple Product Prices`, description, canonical: url, depth: 2 })}
${ld(crumbsLd([["Apple Product Prices", SITE + "/"], ["By product", SITE + "/prices/"], [name, url]]))}
</head>
${top(2, "")}
  <nav class="crumbs" aria-label="Breadcrumb"><ol><li><a href="/">Apple Product Prices</a></li><li><a href="/prices/">By product</a></li><li><a href="/prices/#${ck}">${esc(cat.name)}</a></li><li aria-current="page">${esc(name)}</li></ol></nav>

  <section class="panel">
    <div>
      <div class="eyebrow">${esc(cat.name)} · list prices · ${monthYear(UPDATED)}</div>
      <h1>${esc(title)}</h1>
    </div>
    <p class="lead">${esc(name)} list prices at Apple's online store in the ${n} countries that sell it, from the entry configuration to fully loaded. ${usLine} Converted to US dollars, the ${esc(configLabel)} model is cheapest in ${esc(C[lo.c].label)} (${usd(lo.usd)}${C[lo.c].tax === "excluded" ? " before sales tax" : ""})${cheapestTax && cheapestTax !== lo ? `, or ${esc(C[cheapestTax.c].label)} (${usd(cheapestTax.usd)}) among prices that include tax,` : ""} and most expensive in ${esc(C[hi.c].label)} (${usd(hi.usd)}).</p>
    <ul class="facts">
      <li><span class="k">Cheapest</span><span class="v">${usd(lo.usd)}</span><span class="s">${esc(C[lo.c].label)} · ${esc(fmt(lo.c, lo.local))}${C[lo.c].tax === "excluded" ? " before tax" : ""}</span></li>
${cheapestTax && cheapestTax !== lo ? `      <li><span class="k">Cheapest incl. tax</span><span class="v">${usd(cheapestTax.usd)}</span><span class="s">${esc(C[cheapestTax.c].label)} · ${esc(fmt(cheapestTax.c, cheapestTax.local))}</span></li>\n` : ""}      <li><span class="k">Most expensive</span><span class="v">${usd(hi.usd)}</span><span class="s">${esc(C[hi.c].label)} · ${esc(fmt(hi.c, hi.local))}</span></li>
      <li><span class="k">Countries · configurations</span><span class="v">${n} · ${nConfigs}</span><span class="s">${esc(configLabel)} shown first</span></li>
    </ul>

    <div class="section">
      <h2>${esc(name)} price by country</h2>
      ${entryTable}
    </div>

    <div class="section">
      <h2>All ${esc(name)} configurations</h2>
      <p>Full list price of each configuration in each country, in local currency.${x.p.base ? " Memory and storage upgrades are shown one at a time on the base configuration; to combine them, add both differences to the base price." : ""}</p>
      ${configTables}
    </div>

    <div class="section">
      <h2>Compare and download</h2>
      <ul class="links">
        <li><a href="/world/#${x.worldKey}-0-us">${esc(name)} on the world map</a></li>
        <li><a href="/#${ck}">${esc(cat.name)} price ranges by country</a></li>
        <li><a href="/data/prices.csv">All prices (CSV)</a></li>
        <li><a href="/data/prices.json">All prices (JSON)</a></li>
      </ul>
    </div>
${siblings.length ? `
    <div class="section">
      <h2>Other ${esc(cat.name)} prices</h2>
      <ul class="links">
${siblings.map(y => `        <li><a href="/prices/${y.slug}/">${esc(y.name)}</a></li>`).join("\n")}
      </ul>
    </div>
` : ""}
    <div class="section">
      <h2>About these prices</h2>
      ${NOTES}
    </div>
  </section>
${bottom}`;
}

// ---------- hub page ----------
function hubPage() {
  const url = `${SITE}/prices/`;
  const title = `Apple prices by country: every product in ${ORDER.length} countries`;
  const description = `List prices of ${products.length} current Apple products in the ${ORDER.length} countries with an Apple online store, with the cheapest and most expensive country for each. Checked ${monthYear(UPDATED)}.`;
  const sections = P.order.map(ck => {
    const list = products.filter(x => x.ck === ck);
    if (!list.length) return "";
    return `    <div class="section" id="${ck}">
      <h2>${esc(P.categories[ck].name)}</h2>
      <div class="tw"><table>
        <thead><tr><th>Product</th><th>Entry configuration</th><th class="n">US price</th><th>Cheapest (USD)</th><th>Most expensive (USD)</th></tr></thead>
        <tbody>
${list.map(x => {
      const lo = x.rows[0], hi = x.rows[x.rows.length - 1], us = x.rows.find(r => r.c === "us");
      return `          <tr><th scope="row"><a href="/prices/${x.slug}/">${esc(x.name)}</a></th><td>${esc(x.configLabel)}</td><td class="n">${us ? esc(fmt("us", us.local)) : "–"}</td><td>${esc(C[lo.c].label)} · ${usd(lo.usd)}</td><td>${esc(C[hi.c].label)} · ${usd(hi.usd)}</td></tr>`;
    }).join("\n")}
        </tbody>
      </table></div>
    </div>`;
  }).filter(Boolean).join("\n\n");

  return `${head({ title: `${title} · Apple Product Prices`, description, canonical: url, depth: 1 })}
${ld(crumbsLd([["Apple Product Prices", SITE + "/"], ["By product", url]]))}
</head>
${top(1, "prices")}
  <section class="panel">
    <div>
      <div class="eyebrow">All products · list prices · ${monthYear(UPDATED)}</div>
      <h1>Apple prices by country</h1>
    </div>
    <p class="lead">The list price of every current Apple product in the ${ORDER.length} countries with an Apple online store, read from Apple's own stores. Each product has its own page with every configuration in every country. The table shows the entry configuration, with the cheapest and most expensive country after converting to US dollars.</p>

${sections}

    <div class="section">
      <h2>About these prices</h2>
      ${NOTES}
    </div>
  </section>
${bottom}`;
}

// ---------- write ----------
const out = path.join(ROOT, "prices");
fs.mkdirSync(out, { recursive: true });
// remove pages for products that are no longer listed (only folders this script generated)
for (const d of fs.readdirSync(out, { withFileTypes: true })) {
  if (!d.isDirectory() || seen.has(d.name)) continue;
  const f = path.join(out, d.name, "index.html");
  if (fs.existsSync(f) && fs.readFileSync(f, "utf8").includes(MARK)) {
    fs.rmSync(path.join(out, d.name), { recursive: true });
    console.log("Removed prices/" + d.name);
  }
}
products.forEach((x, i) => {
  fs.mkdirSync(path.join(out, x.slug), { recursive: true });
  fs.writeFileSync(path.join(out, x.slug, "index.html"), productPage(x, i));
});
fs.writeFileSync(path.join(out, "index.html"), hubPage());
console.log(`Wrote prices/ and ${products.length} product pages`);

// sitemap
const urls = [[SITE + "/", "1.0"], [SITE + "/world/", "0.8"], [SITE + "/prices/", "0.9"], ...products.map(x => [`${SITE}/prices/${x.slug}/`, "0.7"])];
fs.writeFileSync(path.join(ROOT, "sitemap.xml"),
  '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
  + urls.map(([u, pr]) => `  <url>\n    <loc>${u}</loc>\n    <lastmod>${UPDATED}</lastmod>\n    <changefreq>monthly</changefreq>\n    <priority>${pr}</priority>\n  </url>\n`).join("")
  + "</urlset>\n");
console.log("Wrote sitemap.xml");

// static product links in the two app pages (between marker comments), so they are crawlable without JavaScript
function linkBlock(prefix) {
  const cols = P.order.map(ck => {
    const list = products.filter(x => x.ck === ck);
    if (!list.length) return "";
    return `      <div><h3>${esc(P.categories[ck].name)}</h3><ul>\n${list.map(x => `        <li><a href="${prefix}prices/${x.slug}/">${esc(x.name)}</a></li>`).join("\n")}\n      </ul></div>`;
  }).filter(Boolean).join("\n");
  return `<!-- product-links: ${MARK} -->
  <nav class="all-products" aria-labelledby="all-products-h">
    <h2 id="all-products-h">Prices by product, in ${ORDER.length} countries</h2>
    <div class="cats">
${cols}
    </div>
  </nav>
  <!-- /product-links -->`;
}
for (const [file, prefix] of [["index.html", ""], ["world/index.html", "../"]]) {
  const f = path.join(ROOT, file);
  let html = fs.readFileSync(f, "utf8");
  const re = /<!-- product-links:[\s\S]*?<!-- \/product-links -->/;
  if (!re.test(html)) throw new Error(`${file}: missing <!-- product-links: --> marker`);
  html = html.replace(re, linkBlock(prefix));
  fs.writeFileSync(f, html);
}
console.log("Updated product links in index.html and world/index.html");

// llms.txt: list the product pages
const llms = path.join(ROOT, "llms.txt");
if (fs.existsSync(llms)) {
  let t = fs.readFileSync(llms, "utf8").replace(/## Product pages\n[\s\S]*?\n\n(?=## )/, "");
  const block = `## Product pages\n\nOne static page per product with every configuration's price in every country, written in the HTML.\n\n- [All products](${SITE}/prices/)\n`
    + products.map(x => `- [${x.name}](${SITE}/prices/${x.slug}/)`).join("\n") + "\n\n";
  t = t.includes("## Source") ? t.replace("## Source", block + "## Source") : t + "\n" + block;
  fs.writeFileSync(llms, t);
  console.log("Updated llms.txt");
}
