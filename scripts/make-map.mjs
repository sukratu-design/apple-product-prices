// Build assets/world-map.js: a projected world map (SVG path strings) for the world comparison page.
// Run once, or after adding a country:
//   npm install --no-save d3-geo@3.1.1 topojson-client@3.1.0 world-atlas@2.0.2
//   node scripts/make-map.mjs
// Natural Earth data via world-atlas (public domain). Equal Earth projection, Antarctica left out.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { geoEqualEarth, geoPath } from 'd3-geo';
import { feature, merge } from 'topojson-client';

const require = createRequire(import.meta.url);
const W = 960, H = 470;
const low = JSON.parse(readFileSync(require.resolve('world-atlas/countries-110m.json'), 'utf8'));
const mid = JSON.parse(readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'));

// ISO 3166 numeric ids, plus where the price marker sits (lon, lat) and which side its label goes
const COUNTRIES = {
  us: { id: '840', at: [-98, 39], label: 'left' },
  ca: { id: '124', at: [-104, 57], label: 'left' },
  uk: { id: '826', at: [-2, 53], label: 'left' },
  ae: { id: '784', at: [54.4, 24.2], label: 'left' },
  in: { id: '356', at: [78.5, 21], label: 'below' },
  sg: { id: '702', at: [103.8, 1.35], label: 'below' },
  jp: { id: '392', at: [138.5, 36.5], label: 'right' },
  au: { id: '036', at: [134, -25], label: 'below' },
};

const notAntarctica = g => g.id !== '010';
const landGeo = merge(low, low.objects.countries.geometries.filter(notAntarctica));
const projection = geoEqualEarth().fitExtent([[8, 8], [W - 8, H - 8]], { type: 'Sphere' });
// trim the empty southern ocean left by removing Antarctica
const path = geoPath(projection).digits(1);

const out = { width: W, height: H, land: path(landGeo), sphere: path({ type: 'Sphere' }), countries: {} };
for (const [k, c] of Object.entries(COUNTRIES)) {
  const pick = topo => topo.objects.countries.geometries.find(g => g.id === c.id);
  const topo = pick(low) ? low : mid; // Singapore only exists in the 50m file
  const f = feature(topo, pick(topo));
  const [x, y] = projection(c.at);
  out.countries[k] = { path: path(f), x: +x.toFixed(1), y: +y.toFixed(1), label: c.label };
}
const js = '// Generated by scripts/make-map.mjs from Natural Earth (world-atlas). Do not edit by hand.\nwindow.WORLD_MAP = ' + JSON.stringify(out) + ';\n';
writeFileSync(new URL('../assets/world-map.js', import.meta.url), js);
console.log('Wrote assets/world-map.js', (js.length / 1024).toFixed(1) + ' KB');
